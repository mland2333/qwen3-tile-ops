#!/usr/bin/env python3
"""Single source of truth for the serve guest/host scratch layout.

The guest includes a generated C++ header (``build/<variant>/serve_layout.h``)
and the host imports this module.  Both use the same formulas, so the ABI
cannot drift silently.

Layout (all offsets are relative to the start of the model blob):

    scratch_end (64-byte aligned)
      cmd         256 B   ServeCmd (bytes 252..255: guest kEnd handshake)
      ptab       8*32 B   one 16-entry page table per item slot
      logits    8*Vocab*4 per-item logits, written directly by lm_head
      ids        8*32*4   per-item token-id slot (no shared ids[pos] race)
      [debug]    sentinel, snap, dump, before

The production guest only touches cmd/ptab/logits.  Debug buffers exist only
in the ``debug`` namespace and are compiled into ``serve_debug.bin`` with
``YAI_SERVE_DEBUG``.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ITEMS = 8
CMD_BYTES = 256
PT_SLOT_BYTES = 32
PT_BYTES = ITEMS * PT_SLOT_BYTES
ID_SLOT_TOKENS = 32
ID_SLOT_BYTES = ID_SLOT_TOKENS * 4
DUMP_STRIDE = 16384
ALIGN = 64
SENTINEL_BYTES = 80 * 4
CPP_NAMES = {
    "scratch": "Scratch",
    "cmd": "Cmd",
    "pt": "PT",
    "abi": "Abi",
    "logits": "Logits",
    "logits_bytes": "LogitsBytes",
    "ids": "Ids",
    "ids_bytes": "IdsBytes",
    "end": "End",
    "sentinel": "Sentinel",
    "snap": "Snap",
    "dump": "Dump",
    "dump_stride": "DumpStride",
    "before": "Before",
}


def align_up(value: int, align: int = ALIGN) -> int:
    return (value + align - 1) // align * align


def read_header(path: Path | str) -> dict[str, int]:
    out: dict[str, int] = {}
    pattern = re.compile(r"\s*inline constexpr (?:int|long) (\w+)\s*=\s*(\d+);")
    for line in Path(path).read_text().splitlines():
        match = pattern.match(line)
        if match:
            out[match.group(1)] = int(match.group(2))
    return out


def layout(header: dict[str, int], debug: bool = False) -> dict[str, int]:
    """Return the scratch offsets for a model header."""
    vocab = int(header["kVocab"])
    scratch = align_up(int(header["kSCRATCH_END"]))
    cmd = scratch
    pt = cmd + CMD_BYTES
    abi = cmd + 252          # guest writes kEnd here; host verifies it
    logits = pt + PT_BYTES
    logits_bytes = ITEMS * vocab * 4
    ids = logits + logits_bytes
    ids_bytes = ITEMS * ID_SLOT_BYTES
    result: dict[str, int] = {
        "scratch": scratch,
        "cmd": cmd,
        "pt": pt,
        "abi": abi,
        "logits": logits,
        "logits_bytes": logits_bytes,
        "ids": ids,
        "ids_bytes": ids_bytes,
        "end": ids + ids_bytes,
    }
    if not debug:
        return result
    sentinel = result["end"]
    snap = sentinel + ITEMS * SENTINEL_BYTES
    dump = snap + logits_bytes
    before = dump + ITEMS * DUMP_STRIDE
    result.update(
        sentinel=sentinel,
        snap=snap,
        dump=dump,
        dump_stride=DUMP_STRIDE,
        before=before,
        end=before + logits_bytes,
    )
    return result


def _emit_namespace(name: str, values: dict[str, int]) -> list[str]:
    lines = [f"namespace {name} {{"]
    for key, value in values.items():
        lines.append(f"inline constexpr long k{CPP_NAMES[key]} = {value};")
    lines.append("}")
    return lines


def emit_cpp(header: dict[str, int]) -> str:
    prod = layout(header, debug=False)
    debug = layout(header, debug=True)
    lines = [
        "// Generated by tools/serve_layout.py; do not edit.",
        "#pragma once",
        "namespace serve_layout {",
        *_emit_namespace("prod", prod),
        "",
        *_emit_namespace("debug", debug),
        "} // namespace serve_layout",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--header", required=True)
    parser.add_argument("--cpp", help="write the generated C++ header here")
    parser.add_argument("--json", action="store_true",
                        help="print the production layout as JSON")
    args = parser.parse_args(argv)
    header = read_header(args.header)
    if args.cpp:
        Path(args.cpp).write_text(emit_cpp(header))
    if args.json:
        import json
        print(json.dumps(layout(header, debug=False), indent=2))
    if not args.cpp and not args.json:
        print(emit_cpp(header), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
