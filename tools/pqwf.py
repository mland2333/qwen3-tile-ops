#!/usr/bin/env python3
"""PQWF: layout, safetensors reader and int8 quantisation helpers.

The blob layout mirrors ``config/model_big.h`` exactly (the checked-in header
was generated by this module before the tool was lost in the Mac -> Ubuntu
migration).  ``Layout.default()`` reproduces it byte for byte; see
``tools/tests/test_layout.py``.

Data conventions (must match ``kernels/``):

* weight matrices are ``[out][in]`` int8, row major (one f32 scale per output
  row, stored in a separate ``f32[n_out]`` array);
* the embedding table is ``[vocab][hidden]`` int8 with one f32 scale per row;
* activations are f32 row major, quantised activations are int8 row major with
  one f32 scale per token;
* RoPE tables are ``[max_seq][head_dim/2]`` f32.
"""

from __future__ import annotations

import json
import struct
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

# MatrixView dtype codes, shared with the ISA (i8=0, u8=1, i32=2, u32=3, f32=4).
DT_I8 = 0
DT_U8 = 1
DT_I32 = 2
DT_U32 = 3
DT_F32 = 4

Q8_MAX = 127
KINV127 = np.float32(1.0) / np.float32(127.0)


# ---------------------------------------------------------------------------
# safetensors
# ---------------------------------------------------------------------------
def read_safetensors(path: str | Path) -> dict[str, np.ndarray]:
    """Reads a safetensors file into numpy arrays (BF16 is widened to f32)."""
    with open(path, "rb") as handle:
        header_len = struct.unpack("<Q", handle.read(8))[0]
        header = json.loads(handle.read(header_len))
        base = 8 + header_len
        out: dict[str, np.ndarray] = {}
        for name, info in header.items():
            if name == "__metadata__":
                continue
            dtype = info["dtype"]
            shape = tuple(info["shape"])
            start, end = info["data_offsets"]
            handle.seek(base + start)
            raw = handle.read(end - start)
            if dtype == "BF16":
                bits = np.frombuffer(raw, dtype=np.uint16).astype(np.uint32) << 16
                out[name] = bits.view(np.float32).reshape(shape)
            elif dtype == "F16":
                out[name] = np.frombuffer(raw, dtype=np.float16).astype(np.float32).reshape(shape)
            elif dtype == "F32":
                out[name] = np.frombuffer(raw, dtype=np.float32).reshape(shape)
            else:
                raise ValueError(f"unsupported dtype {dtype} for {name}")
        return out


# ---------------------------------------------------------------------------
# int8 quantisation (per output row, symmetric, magnitude 127)
# ---------------------------------------------------------------------------
def quantize_rows(matrix: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Per-row symmetric int8 quantisation.

    ``scale[r] = absmax(matrix[r]) * (1/127)`` and
    ``q[r][c] = rne(matrix[r][c] / scale[r])`` saturated to [-127, 127]
    (NaN -> 0), matching ``aquant.rows.scale.q8s32`` with a provided scale.
    """
    matrix = np.asarray(matrix, dtype=np.float32)
    if matrix.ndim != 2:
        raise ValueError("quantize_rows expects a 2-D matrix")
    absmax = np.max(np.abs(matrix), axis=1).astype(np.float32)
    scale = (absmax * KINV127).astype(np.float32)
    with np.errstate(invalid="ignore", divide="ignore"):
        quotient = (matrix / scale[:, None]).astype(np.float32)
    quant = np.rint(quotient).astype(np.float32)
    quant = np.where(np.isnan(quotient), np.float32(0.0), quant)
    quant = np.clip(quant, -Q8_MAX, Q8_MAX)
    return quant.astype(np.int8), scale


# ---------------------------------------------------------------------------
# blob layout
# ---------------------------------------------------------------------------
@dataclass
class Layout:
    hidden: int = 1024
    layers: int = 28
    heads: int = 16
    kv_heads: int = 8
    head_dim: int = 128
    inter: int = 3072
    vocab: int = 151936
    seq: int = 32
    max_seq: int = 256
    offsets: dict[str, int] = field(default_factory=dict, init=False)

    @property
    def half(self) -> int:
        return self.head_dim // 2

    @property
    def q_width(self) -> int:
        return self.heads * self.head_dim

    @property
    def kv_width(self) -> int:
        return self.kv_heads * self.head_dim

    @property
    def layer_norm_stride(self) -> int:
        return 4 * (self.hidden + self.head_dim + self.head_dim + self.hidden)

    @property
    def kv_scale_off(self) -> int:
        return self.max_seq * self.kv_width

    @property
    def kv_stride(self) -> int:
        return 2 * (self.kv_scale_off + 4 * self.max_seq)

    def compute(self) -> "Layout":
        off = 0
        o: dict[str, int] = {}

        def place(name: str, size: int) -> int:
            nonlocal off
            o[name] = off
            off += size
            return o[name]

        place("kIDS", 4 * self.max_seq)
        place("kCTRL", 16)
        place("kX", 4 * self.seq * self.hidden)
        place("kEMB", self.vocab * self.hidden + 4 * self.vocab)
        place("kLM", self.vocab * self.hidden + 4 * self.vocab)
        place("kNF", 4 * self.hidden)
        place("kCOS", 4 * self.max_seq * self.half)
        place("kSIN", 4 * self.max_seq * self.half)

        o["kLAYERW_BASE"] = off
        layer_start = off
        place("kLQ", self.q_width * self.hidden)
        place("kLQ_SCALE", 4 * self.q_width)
        place("kLK", self.kv_width * self.hidden)
        place("kLK_SCALE", 4 * self.kv_width)
        place("kLV", self.kv_width * self.hidden)
        place("kLV_SCALE", 4 * self.kv_width)
        place("kLO", self.hidden * self.q_width)
        place("kLO_SCALE", 4 * self.hidden)
        place("kLG", self.inter * self.hidden)
        place("kLG_SCALE", 4 * self.inter)
        place("kLU", self.inter * self.hidden)
        place("kLU_SCALE", 4 * self.inter)
        place("kLD", self.hidden * self.inter)
        place("kLD_SCALE", 4 * self.hidden)
        o["kLAYERW_STRIDE"] = off - layer_start
        off = layer_start + self.layers * o["kLAYERW_STRIDE"]

        o["kLAYERN_BASE"] = off
        o["kLAYERN_STRIDE"] = self.layer_norm_stride
        off += self.layers * self.layer_norm_stride
        o["kN1"] = o["kLAYERN_BASE"]
        o["kNQ"] = o["kLAYERN_BASE"] + 4 * self.hidden
        o["kNK"] = o["kNQ"] + 4 * self.head_dim
        o["kN2"] = o["kNK"] + 4 * self.head_dim

        place("kLOGITS", 4 * self.seq * self.vocab)
        o["kBLOCK_END"] = off
        off = (off + 0xFFFF) & ~0xFFFF  # activations start on a 64 KiB boundary

        place("kH", 4 * self.seq * self.hidden)
        place("kH8", self.seq * self.hidden)
        place("kHS", 256)
        place("kQ", 4 * self.seq * self.q_width)
        place("kK", 4 * self.seq * self.kv_width)
        place("kV", 4 * self.seq * self.kv_width)
        place("kQ8", self.seq * self.q_width)
        place("kK8", self.seq * self.kv_width)
        place("kV8", self.seq * self.kv_width)
        place("kQS", 256)
        place("kKS", 256)
        place("kVS", 256)
        place("kATTN", 4 * self.seq * self.q_width)
        place("kO", 4 * self.seq * self.hidden)
        place("kO8", self.seq * self.q_width)
        place("kOS", 256)
        place("kG", 4 * self.seq * self.inter)
        place("kU", 4 * self.seq * self.inter)
        place("kSW", 4 * self.seq * self.inter)
        place("kS8", self.seq * self.inter)
        place("kSS", 256)
        place("kARGF", 256)
        place("kARGI", 256)
        o["kKV_BASE"] = off  # the KV cache itself is sized by the layer count
        o["kKV_SOFF"] = self.kv_scale_off
        o["kKV_VOFF"] = self.kv_scale_off + 4 * self.max_seq
        o["kKV_STRIDE"] = self.kv_stride
        off += self.layers * self.kv_stride
        o["kSCRATCH_END"] = off

        self.offsets = o
        return self

    # -- scalar constants written to the header -----------------------------
    def constants(self) -> dict[str, int]:
        return {
            "kHidden": self.hidden,
            "kLayers": self.layers,
            "kHeads": self.heads,
            "kKvHeads": self.kv_heads,
            "kHeadDim": self.head_dim,
            "kInter": self.inter,
            "kVocab": self.vocab,
            "kSeq": self.seq,
            "kMaxSeq": self.max_seq,
            "kHalf": self.half,
        }

    @classmethod
    def from_header(cls, path: str | Path) -> "Layout":
        """Rebuild the layout (fields and offsets) from a generated header."""
        import re
        text = Path(path).read_text()
        ints = {k: int(v) for k, v in re.findall(
            r"inline constexpr int (\w+)\s*=\s*(\d+);", text)}
        longs = {k: int(v) for k, v in re.findall(
            r"inline constexpr long (\w+)\s*=\s*(\d+);", text)}
        layout = cls(hidden=ints["kHidden"], layers=ints["kLayers"],
                     heads=ints["kHeads"], kv_heads=ints["kKvHeads"],
                     head_dim=ints["kHeadDim"], inter=ints["kInter"],
                     vocab=ints["kVocab"], seq=ints["kSeq"], max_seq=ints["kMaxSeq"])
        layout.offsets = longs
        return layout

    def header_text(self) -> str:
        lines = ["#pragma once", "namespace mb {"]
        for name, value in self.constants().items():
            lines.append(f"inline constexpr int {name} = {value};")
        ordered = [
            "kIDS", "kCTRL", "kX", "kEMB", "kLM", "kNF", "kCOS", "kSIN",
            "kLAYERW_BASE", "kLAYERW_STRIDE",
            "kLQ", "kLQ_SCALE", "kLK", "kLK_SCALE", "kLV", "kLV_SCALE",
            "kLO", "kLO_SCALE", "kLG", "kLG_SCALE", "kLU", "kLU_SCALE",
            "kLD", "kLD_SCALE",
            "kLAYERN_BASE", "kLAYERN_STRIDE",
            "kN1", "kNQ", "kNK", "kN2",
            "kLOGITS", "kBLOCK_END",
            "kH", "kH8", "kHS", "kQ", "kK", "kV", "kQ8", "kK8", "kV8",
            "kQS", "kKS", "kVS", "kATTN", "kO", "kO8", "kOS",
            "kG", "kU", "kSW", "kS8", "kSS", "kARGF", "kARGI",
            "kKV_BASE", "kKV_STRIDE", "kKV_VOFF", "kKV_SOFF", "kSCRATCH_END",
        ]
        for name in ordered:
            lines.append(f"inline constexpr long {name} = {self.offsets[name]};")
        lines.append("}")
        lines.append("")
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# streaming readers / writer
# ---------------------------------------------------------------------------
class SafeTensors:
    """Random access to a safetensors file without loading it into memory."""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        with open(self.path, "rb") as handle:
            header_len = struct.unpack("<Q", handle.read(8))[0]
            self.header = json.loads(handle.read(header_len))
        self.base = 8 + header_len
        self.data = np.memmap(self.path, dtype=np.uint8, mode="r")

    def names(self) -> list[str]:
        return [name for name in self.header if name != "__metadata__"]

    def info(self, name: str) -> dict:
        return self.header[name]

    def raw(self, name: str) -> np.ndarray:
        """The tensor as a typed view on the file (BF16 stays uint16)."""
        info = self.header[name]
        dtype = info["dtype"]
        shape = tuple(info["shape"])
        start, end = info["data_offsets"]
        elem = {"BF16": np.uint16, "F16": np.uint16, "F32": np.float32}[dtype]
        return np.frombuffer(self.data, dtype=elem, count=(end - start) // elem().itemsize,
                             offset=self.base + start).reshape(shape)

    def block_f32(self, name: str, r0: int, r1: int) -> np.ndarray:
        """Rows [r0, r1) of a 2-D tensor as f32."""
        info = self.header[name]
        dtype = info["dtype"]
        raw = self.raw(name)[r0:r1]
        if dtype == "BF16":
            return ((raw.astype(np.uint32) << 16).view(np.float32)).astype(np.float32)
        if dtype == "F16":
            return raw.astype(np.float32)
        return raw.astype(np.float32)

    def vector_f32(self, name: str) -> np.ndarray:
        info = self.header[name]
        raw = self.raw(name)
        if info["dtype"] == "BF16":
            return ((raw.astype(np.uint32) << 16).view(np.float32)).astype(np.float32)
        return raw.astype(np.float32)


class Blob:
    """A file-backed little-endian byte buffer addressed by absolute offsets."""

    def __init__(self, path: str | Path, size: int):
        self.path = Path(path)
        with open(self.path, "wb") as handle:
            handle.truncate(size)
        self.buf = np.memmap(self.path, dtype=np.uint8, mode="r+", shape=(size,))

    def put(self, offset: int, data) -> None:
        if isinstance(data, (bytes, bytearray)):
            raw = np.frombuffer(data, dtype=np.uint8)
        else:
            raw = np.ascontiguousarray(data).view(np.uint8).reshape(-1)
        self.buf[offset:offset + raw.size] = raw

    def flush(self) -> None:
        self.buf.flush()
        del self.buf


def quantize_into(st: "SafeTensors", name: str, blob: Blob, q_offset: int, s_offset: int,
                  rows: int, cols: int, chunk: int = 2048) -> None:
    """Per-row int8 quantisation written straight into the blob."""
    for r0 in range(0, rows, chunk):
        r1 = min(rows, r0 + chunk)
        block = st.block_f32(name, r0, r1)
        absmax = np.max(np.abs(block), axis=1).astype(np.float32)
        scale = (absmax * KINV127).astype(np.float32)
        with np.errstate(invalid="ignore", divide="ignore"):
            quotient = (block / scale[:, None]).astype(np.float32)
        quant = np.rint(quotient).astype(np.float32)
        quant = np.where(np.isnan(quotient), np.float32(0.0), quant)
        quant = np.clip(quant, -Q8_MAX, Q8_MAX)
        blob.put(q_offset + r0 * cols, quant.astype(np.int8))
        blob.put(s_offset + r0 * 4, scale)
